    private static readonly SnipLevel[] Parsed = ParseAll();

    public static SnipLevel Get(int level) => Parsed[Math.Clamp(level, 1, Count) - 1];

    private static SnipLevel[] ParseAll()
    {
        var levels = new SnipLevel[Sources.Length];
        for (var index = 0; index < Sources.Length; index++)
        {
            if (!SnipLevel.TryParse(Sources[index], out var level, out var error))
            {
                throw new InvalidOperationException(string.Concat("Snip level ", Sources[index], ": ", error));
            }

            levels[index] = level;
        }

        return levels;
    }
